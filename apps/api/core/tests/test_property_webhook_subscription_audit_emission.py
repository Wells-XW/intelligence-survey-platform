"""Property test P19 (webhook subscription portion): audit emission for terminal transitions.

Per design §Property 19 (Requirements 7.2, 9.4), every terminal transition
on a webhook subscription — create, update, rotate-secret, delete — must
append exactly one row to ``audit_logs`` whose ``action`` matches the
canonical verb, whose ``user_id`` is the actor, and whose
``resource_type`` / ``resource_id`` reference the subscription.

This module exercises the subscription portion of Property 19. The
companion sub-tasks 4.7, 8.7, 11.11, and 13.5 cover the api-key,
webhook-delivery, export, and rate-limit portions respectively. Per
design §Component 3, the four canonical verbs are
``webhook.subscription.create``, ``webhook.subscription.update``,
``webhook.subscription.rotate_secret``, and
``webhook.subscription.delete``.

Strategy
--------

For every Hypothesis example we:

1. Insert a fresh JWT-authenticated owner via a per-example
   committing session so the route can read it back via the API
   stack. A unique email per example keeps owners from colliding
   across the function-scoped fixture lifetime.
2. Hit ``POST /api/v1/webhooks/`` to create a subscription and
   capture its id. The ``create`` action is part of the per-example
   sequence by construction — it has to be the first transition
   because every subsequent verb references the same subscription
   id.
3. Apply a Hypothesis-generated sequence drawn from
   ``{update, rotate_secret, delete}``. Soft-delete is terminal in
   the lifecycle (the route's idempotency check skips the audit
   write on a second delete, per
   ``app.api.v1.webhooks.delete_webhook_subscription``); we model
   that by truncating the action sequence at the first ``delete``.
   Updates carry a ``description`` change so the route's
   ``changed`` dict is non-empty and the audit row is emitted (the
   route also skips the audit write on a no-op patch).
4. Query ``audit_logs`` filtered by the subscription id and the
   four canonical verbs and assert (a) exactly one row per executed
   transition, (b) verb labels match the executed action types,
   (c) ``user_id`` equals the owner, (d) ``resource_type`` is
   ``webhook_subscription``, and (e) ``resource_id`` equals the
   subscription id.

Session-management note
-----------------------

The shared ``conftest.db_session`` fixture wraps the test in
``async with session.begin() as transaction:`` and rolls back at
teardown. That pattern is incompatible with property tests that
hit committing routes across many Hypothesis examples: the first
route ``db.commit()`` closes the wrapper's inner transaction, and
the second example then trips
``InvalidRequestError: Can't operate on closed transaction inside
context manager`` on the next session operation. To avoid that
brittleness we build a per-test session factory bound to the
function-scoped ``test_engine`` and override
:func:`app.database.get_db` ourselves, giving each route call a
fresh, autocommit-style session and using a separate fresh session
for in-test verification queries.

# Feature: api-platform-export, Property 19: Audit emission for terminal transitions
# Validates: Requirements 7.2, 9.4
"""

